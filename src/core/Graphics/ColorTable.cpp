  {
  static ColorTable table;
  return table;
  }

  ColorTable::ColorTable()
  :
  _colors(),
  _next(1000)
  {
  for (const DefaultColor & d : defaults) _colors[d.index] = Entry{ Color(d.red, d.green, d.blue), String(d.name) };
  }

  Color ColorTable::color(int index) const
  {
  auto found = _colors.find(index);
  return found == _colors.end() ? Color(0.0f, 0.0f, 0.0f) : found->second.color;
  }

  void ColorTable::rgb(int index, float & red, float & green, float & blue) const
  {
  Color c = color(index);
  red = c.red; green = c.green; blue = c.blue;
  }

  int ColorTable::index(const Color & color)
  {
  const float tolerance = 1.0f/512.0f;
  for (const auto & e : _colors)
    {
    const Color & c = e.second.color;
    if (std::fabs(c.red - color.red) < tolerance && std::fabs(c.green - color.green) < tolerance
        && std::fabs(c.blue - color.blue) < tolerance) return e.first;
    }
  while (_colors.count(_next)) _next++;
  _colors[_next] = Entry{ Color(color.red, color.green, color.blue), String() };
  return _next++;
  }

  void ColorTable::set(int index, const Color & color, const String & name)
  {
  _colors[index] = Entry{ Color(color.red, color.green, color.blue), name };
  if (index >= _next) _next = index + 1;
  }

  String ColorTable::name(int index) const
  {
  auto found = _colors.find(index);
  if (found == _colors.end()) return String("unknown");
  if (!found->second.name.isNull() && !found->second.name.str().empty()) return found->second.name;
  const Color & c = found->second.color;
  char text[16];
  std::snprintf(text, sizeof(text), "#%02x%02x%02x", int(std::lround(c.red*255)), int(std::lround(c.green*255)), int(std::lround(c.blue*255)));
  return String(text);
  }

